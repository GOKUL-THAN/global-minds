// ── Export the unified course catalog ─────────────────────────
export const allCourses: Course[] = courses.map(course => {
  const image = `/images/courses/${course.slug}.jpg`;
  return { ...course, thumbnail: image, banner: image };
});

// ── Helper functions ──────────────────────────────────────────
export const getCourseBySlug = (slug: string): Course | undefined => {
  if (slug === 'software-testing' || slug === 'automation-testing') {
    return allCourses.find(c => c.slug === 'software-and-automation-testing')
      || allCourses.find(c => c.slug === slug);
  }
  return allCourses.find(c => c.slug === slug);
};

export const getCoursesByCategory = (categorySlug: string): Course[] => {
  let targetCat = categorySlug;
  if (categorySlug === 'software-testing' || categorySlug === 'automation-testing') {
    targetCat = 'software-and-automation-testing';
  } else if (categorySlug === 'machine-learning') {
    targetCat = 'artificial-intelligence';
  }
  return allCourses.filter(c =>
    (c.category === targetCat || c.category === categorySlug) && c.status === 'active'
  );
};

export const getFeaturedCourses = (): Course[] =>
  allCourses.filter(c => c.featured && c.status === 'active');

export const getTrendingCourses = (): Course[] =>
  allCourses.filter(c => c.trending && c.status === 'active');

export const getPopularCourses = (): Course[] =>
  allCourses.filter(c => c.popular && c.status === 'active');

export const searchCourses = (query: string): Course[] => {
  const q = query.toLowerCase();
  return allCourses.filter(c =>
    c.title.toLowerCase().includes(q) ||
    c.shortDescription.toLowerCase().includes(q) ||
    c.category.toLowerCase().includes(q) ||
    c.tags.some(t => t.toLowerCase().includes(q)) ||
    c.skills.some(s => s.toLowerCase().includes(q))
  );
};

export const getRelatedCourses = (courseSlug: string): Course[] => {
  const course = getCourseBySlug(courseSlug);
  if (!course) return [];
  // Find courses in same category, excluding current
  const sameCat = allCourses.filter(
    c => c.category === course.category && c.slug !== courseSlug && c.status === 'active'
  ).slice(0, 4);
  if (sameCat.length >= 4) return sameCat;
  // Supplement with related slugs
  const fromRelated = course.relatedCourses
    .map(s => getCourseBySlug(s))
    .filter((c): c is Course => c !== undefined && c.slug !== courseSlug);
  const merged = [...sameCat, ...fromRelated];
  const seen = new Set<string>();
  return merged.filter(c => {
    if (seen.has(c.slug)) return false;
    seen.add(c.slug);
    return true;
  }).slice(0, 4);
};